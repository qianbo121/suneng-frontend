import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.join(root, 'docs/furnace-animations-20260909/src');
const target = path.join(root, 'frontend/public/animations/furnaces/v3');
const files = ['engine.js', 'refinement.js', 'batch-models.js', 'continuous-models.js', 'rotary-model.js', 'additional-models.js', 'site-player.js'];
const parts = await Promise.all(files.map((name) => readFile(path.join(source, name), 'utf8')));
parts[0] = parts[0].replace('https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.module.js', './three.module.min.js');
const output = `// Generated by scripts/build-furnace-animation.mjs from the approved furnace models.\n${parts.join('\n')}`;
await mkdir(target, { recursive: true });
await writeFile(path.join(target, 'renderer.js'), output);
console.log(`Furnace renderer: ${Buffer.byteLength(output)} bytes; dependencies served locally.`);
